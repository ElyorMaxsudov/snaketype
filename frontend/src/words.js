export function getRandomWords(language = 'uzbek_latin', count = 30, options = {}) {
  const { includePunctuation = false, includeNumbers = false } = options;
  const list = wordsData[language] || wordsData.uzbek_latin;
  const words = [];

  const punctuationMarks = ['.', ',', '!', '?', ';', ':', '"', '-'];

  for (let i = 0; i < count; i++) {
    // Agar numbers yoqilgan bo'lsa har 5-6 ta so'zdan bittasiga son qo'shish
    if (includeNumbers && Math.random() < 0.15) {
      const num = Math.floor(10 + Math.random() * 990);
      words.push(num.toString());
      continue;
    }

    const randomIndex = Math.floor(Math.random() * list.length);
    let word = list[randomIndex];

    // Agar punctuation yoqilgan bo'lsa
    if (includePunctuation) {
      // Birinchi harfni bosh harf qilish ehtimoli
      if (i === 0 || Math.random() < 0.2) {
        word = word.charAt(0).toUpperCase() + word.slice(1);
      }
      // Oxiriga tinish belgisi qo'yish
      if (Math.random() < 0.25) {
        const p = punctuationMarks[Math.floor(Math.random() * punctuationMarks.length)];
        word = word + p;
      }
    }

    words.push(word);
  }

  return words;
}
